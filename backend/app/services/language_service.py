# Conversations keep the tutor's three-step level; map CEFR onto it for role-plays.
CEFR_TO_LEVEL = {
    CefrLevel.A1: LearningLevel.BEGINNER,
    CefrLevel.A2: LearningLevel.BEGINNER,
    CefrLevel.B1: LearningLevel.INTERMEDIATE,
    CefrLevel.B2: LearningLevel.INTERMEDIATE,
    CefrLevel.C1: LearningLevel.ADVANCED,
    CefrLevel.C2: LearningLevel.ADVANCED,
}

# Skills whose content is generated by the model and marked on submission.
GENERATED = {
    PracticeSkill.GRAMMAR: (cs.GrammarLesson, prompts.GRAMMAR_SYSTEM, cs.validate_grammar),
    PracticeSkill.LISTENING: (cs.Passage, prompts.LISTENING_SYSTEM, cs.validate_passage),
    PracticeSkill.READING: (cs.Passage, prompts.READING_SYSTEM, cs.validate_passage),
    PracticeSkill.WRITING: (cs.WritingTask, prompts.WRITING_TASK_SYSTEM, cs.validate_writing_task),
    PracticeSkill.SPEAKING: (cs.SpeakingSet, prompts.SPEAKING_SYSTEM, cs.validate_speaking),
}
SECRET_FIELDS = ("answer", "explanation")


def _now() -> datetime:
    return datetime.now(UTC)


# --- enrolment ----------------------------------------------------------------------


async def list_courses(session: AsyncSession, user_id: uuid.UUID) -> list[CourseOut]:
    enrollments = {
        e.language: e
        for e in await session.scalars(
            select(LanguageEnrollment).where(LanguageEnrollment.user_id == user_id)
        )
    }
    word_rows = await session.execute(
        select(
            VocabItem.language,
            func.count(),
            func.count().filter(VocabItem.due_at <= _now()),
            func.max(VocabItem.last_reviewed_at),
        )
        .where(VocabItem.user_id == user_id)
        .group_by(VocabItem.language)
    )
    words = {lang: (total, due, last) for lang, total, due, last in word_rows}
    practice_rows = await session.execute(
        select(PracticeSession.language, func.max(PracticeSession.created_at))
        .where(PracticeSession.user_id == user_id)
        .group_by(PracticeSession.language)
    )
    practised = dict(practice_rows.all())

    courses = []
    for code, name in prompts.COURSE_LANGUAGE_NAMES.items():
        total, due, reviewed = words.get(code, (0, 0, None))
        enrollment = enrollments.get(code)
        last = max((d for d in (reviewed, practised.get(code)) if d), default=None)
        courses.append(
            CourseOut(
                code=code,
                name=name.split(" (")[0],
                enrolled=enrollment is not None,
                level=enrollment.level if enrollment else None,
                words=total,
                due=due,
                last_practised=last,
            )
        )
    return courses


async def enroll(
    session: AsyncSession, user_id: uuid.UUID, language: str, level: CefrLevel
) -> LanguageEnrollment:
    """Start a course, or change its level."""
    await session.execute(
        insert(LanguageEnrollment)
        .values(user_id=user_id, language=language, level=level)
        .on_conflict_do_update(
            constraint="uq_language_enrollments_user_id",
            set_={"level": level, "updated_at": func.now()},
        )
    )
    await session.commit()
    return await _enrollment(session, user_id, language)


async def _enrollment(session: AsyncSession, user_id: uuid.UUID, language: str):
    enrollment = await session.scalar(
        select(LanguageEnrollment).where(
            LanguageEnrollment.user_id == user_id, LanguageEnrollment.language == language
        )
    )
    if enrollment is None:
        raise AppError(409, "not_enrolled", "Choose your level for this language first.")
    return enrollment


# --- vocabulary ---------------------------------------------------------------------


async def generate_vocabulary(
    session: AsyncSession, llm: LLMProvider, user: User, language: str, topic: str | None
) -> list[VocabItem]:
    """Ask the model for new words at the learner's level and add them to their deck."""
    enrollment = await _enrollment(session, user.id, language)
    known = list(
        await session.scalars(
            select(VocabItem.word)
            .where(VocabItem.user_id == user.id, VocabItem.language == language)
            .order_by(VocabItem.created_at.desc())
            .limit(80)
        )
    )
    result = await llm.parse(
        system=prompts.VOCAB_SYSTEM,
        messages=[
            ChatMessage("user", prompts.vocab_request(language, enrollment.level, topic, known))
        ],
        schema=cs.VocabList,
    )
    words = cs.validate_vocab(result.value).words
    inserted = await session.scalars(
        insert(VocabItem)
        .values(
            [
                {
                    "user_id": user.id,
                    "language": language,
                    "word": w.word,
                    "reading": w.reading or None,
                    "meaning": w.meaning,
                    "example": w.example or None,
                    "example_translation": w.example_translation or None,
                    "level": enrollment.level,
                    "topic": topic,
                }
                for w in words
            ]
        )
        .on_conflict_do_nothing(constraint="uq_vocab_items_user_id")
        .returning(VocabItem)
    )
    added = list(inserted)
    await session.commit()
    return added


async def list_vocabulary(
    session: AsyncSession, user_id: uuid.UUID, language: str, *, due_only: bool, limit: int
) -> list[VocabItem]:
    query = select(VocabItem).where(VocabItem.user_id == user_id, VocabItem.language == language)
    if due_only:
        query = query.where(VocabItem.due_at <= _now()).order_by(VocabItem.due_at)
    else:
        query = query.order_by(VocabItem.created_at.desc())
    return list(await session.scalars(query.limit(limit)))


async def _vocab_item(session: AsyncSession, user_id: uuid.UUID, item_id: uuid.UUID) -> VocabItem:
    item = await session.get(VocabItem, item_id)
    if item is None or item.user_id != user_id:
        raise NotFound("Word")
    return item


async def review_vocabulary(
    session: AsyncSession, user_id: uuid.UUID, item_id: uuid.UUID, grade: str
) -> VocabItem:
    item = await _vocab_item(session, user_id, item_id)
    now = _now()
    nxt = schedule_review(
        ease=item.ease,
        interval_days=item.interval_days,
        repetitions=item.repetitions,
        lapses=item.lapses,
        grade=grade,
        now=now,
    )
    item.ease, item.interval_days, item.repetitions = nxt.ease, nxt.interval_days, nxt.repetitions
    item.lapses, item.due_at, item.last_reviewed_at = nxt.lapses, nxt.due_at, now
    await session.commit()
    await session.refresh(item)
    return item


async def delete_vocabulary(session: AsyncSession, user_id: uuid.UUID, item_id: uuid.UUID):
    await session.delete(await _vocab_item(session, user_id, item_id))
    await session.commit()


# --- practice -----------------------------------------------------------------------


def _public_content(practice: PracticeSession) -> dict:
    """Session content as the learner may see it: no answers until it has been submitted."""
    if practice.completed_at is not None:
        return practice.content
    content = dict(practice.content)
    for key in ("exercises", "questions"):
        if key in content:
            content[key] = [
                {k: v for k, v in item.items() if k not in SECRET_FIELDS} for item in content[key]
            ]
    return content


def session_out(practice: PracticeSession) -> PracticeSessionOut:
    return PracticeSessionOut(
        id=practice.id,
        language=practice.language,
        level=practice.level,
        skill=practice.skill,
        topic=practice.topic,
        content=_public_content(practice),
        answers=practice.answers,
        result=practice.result,
        score=practice.score,
        conversation_id=practice.conversation_id,
        created_at=practice.created_at,
        completed_at=practice.completed_at,
    )


def summary_out(practice: PracticeSession) -> PracticeSummaryOut:
    title = practice.content.get("title") or practice.content.get("scenario") or practice.skill
    return PracticeSummaryOut(
        id=practice.id,
        skill=practice.skill,
        level=practice.level,
        title=str(title),
        score=practice.score,
        conversation_id=practice.conversation_id,
        created_at=practice.created_at,
        completed_at=practice.completed_at,
    )


async def start_practice(
    session: AsyncSession, llm: LLMProvider, user: User, language: str, data: PracticeStartIn
) -> PracticeSession:
    enrollment = await _enrollment(session, user.id, language)
    level = enrollment.level
    practice = PracticeSession(
        user_id=user.id, language=language, level=level, skill=data.skill, topic=data.topic
    )
    if data.skill == PracticeSkill.CONVERSATION:
        scenario = data.scenario or data.topic or "Meeting someone new and chatting"
        name = prompts.COURSE_LANGUAGE_NAMES[language].split(" (")[0]
        conversation = Conversation(
            user_id=user.id,
            title=f"{name} role-play · {scenario}"[:200],
            mode=ConversationMode.VOICE,
            language=language,
            level=CEFR_TO_LEVEL[level],
        )
        session.add(conversation)
        await session.flush()
        practice.conversation_id = conversation.id
        practice.content = {"scenario": scenario}
    else:
        schema, system, validate = GENERATED[data.skill]
        result = await llm.parse(
            system=system,
            messages=[ChatMessage("user", prompts.content_request(language, level, data.topic))],
            schema=schema,
        )
        practice.content = validate(result.value).model_dump()
        logger.info(
            "practice generated skill=%s model=%s out=%s",
            data.skill,
            result.model,
            result.usage.output_tokens,
        )
    session.add(practice)
    await session.commit()
    await session.refresh(practice)
    return practice


async def get_practice(
    session: AsyncSession, user_id: uuid.UUID, practice_id: uuid.UUID
) -> PracticeSession:
    practice = await session.get(PracticeSession, practice_id)
    if practice is None or practice.user_id != user_id:
        raise NotFound("Practice session")
    return practice


async def list_practice(
    session: AsyncSession,
    user_id: uuid.UUID,
    language: str,
    *,
    skill: PracticeSkill | None,
    limit: int,
) -> list[PracticeSession]:
    query = select(PracticeSession).where(
        PracticeSession.user_id == user_id, PracticeSession.language == language
    )
    if skill is not None:
        query = query.where(PracticeSession.skill == skill)
    return list(
        await session.scalars(query.order_by(PracticeSession.created_at.desc()).limit(limit))
    )


async def submit_practice(
    session: AsyncSession,
    llm: LLMProvider,
    user_id: uuid.UUID,
    practice_id: uuid.UUID,
    data: PracticeSubmitIn,
) -> PracticeSession:
    practice = await get_practice(session, user_id, practice_id)
    if practice.completed_at is not None:
        raise AppError(409, "already_submitted", "This practice has already been marked.")
    skill, content = practice.skill, practice.content

    if skill in (PracticeSkill.GRAMMAR, PracticeSkill.LISTENING, PracticeSkill.READING):
        items = content["exercises" if skill == PracticeSkill.GRAMMAR else "questions"]
        answers = _required(data.answers, "answers", len(items))
        score, marked = grade_exercises(items, answers)
        practice.answers, practice.result = {"answers": answers}, {"items": marked}
    elif skill == PracticeSkill.SPEAKING:
        transcripts = _required(data.transcripts, "transcripts", len(content["phrases"]))
        score, marked = grade_speaking(content["phrases"], transcripts)
        practice.answers, practice.result = {"transcripts": transcripts}, {"items": marked}
    elif skill == PracticeSkill.WRITING:
        if not data.text:
            raise AppError(422, "missing_text", "Write your answer first.")
        result = await llm.parse(
            system=prompts.WRITING_FEEDBACK_SYSTEM,
            messages=[
                ChatMessage(
                    "user",
                    prompts.feedback_request(practice.language, practice.level, content, data.text),
                )
            ],
            schema=cs.WritingFeedback,
        )
        feedback = cs.validate_feedback(result.value)
        score = feedback.score / 100
        practice.answers = {"text": data.text, "words": len(data.text.split())}
        practice.result = feedback.model_dump()
    else:
        raise AppError(400, "not_submittable", "Conversation practice isn't marked.")

    practice.score = round(score, 3)
    practice.completed_at = _now()
    await session.commit()
    await session.refresh(practice)
    return practice


def _required(values: list[str] | None, field: str, expected: int) -> list[str]:
    if values is None or len(values) != expected:
        raise AppError(422, f"invalid_{field}", f"Send exactly {expected} {field}.")
    return values


# --- progress -----------------------------------------------------------------------


async def progress(session: AsyncSession, user_id: uuid.UUID, language: str) -> ProgressOut:
    enrollment = await session.scalar(
        select(LanguageEnrollment).where(
            LanguageEnrollment.user_id == user_id, LanguageEnrollment.language == language
        )
    )
    now = _now()
    total, learned, mastered, due = (
        await session.execute(
            select(
                func.count(),
                func.count().filter(VocabItem.repetitions >= 1),
                func.count().filter(VocabItem.interval_days >= 21),
                func.count().filter(VocabItem.due_at <= now),
            ).where(VocabItem.user_id == user_id, VocabItem.language == language)
        )
    ).one()

    rows = await session.execute(
        select(
            PracticeSession.skill,
            func.count(),
            func.count(PracticeSession.completed_at),
            func.avg(PracticeSession.score),
            func.max(PracticeSession.created_at),
        )
        .where(PracticeSession.user_id == user_id, PracticeSession.language == language)
        .group_by(PracticeSession.skill)
    )
    stats = {
        skill: SkillStats(
            sessions=sessions,
            completed=completed,
            average_score=round(avg, 3) if avg is not None else None,
            last_practised=last,
        )
        for skill, sessions, completed, avg, last in rows
    }
    skills = {
        skill: stats.get(
            skill, SkillStats(sessions=0, completed=0, average_score=None, last_practised=None)
        )
        for skill in PracticeSkill
    }

    # Active days: reviewing a word, finishing practice, or starting a role-play.
    since = now - timedelta(days=60)
    review_days = await session.scalars(
        select(func.date(VocabItem.last_reviewed_at)).where(
            VocabItem.user_id == user_id,
            VocabItem.language == language,
            VocabItem.last_reviewed_at >= since,
        )
    )
    practice_days = await session.scalars(
        select(
            func.date(func.coalesce(PracticeSession.completed_at, PracticeSession.created_at))
        ).where(
            PracticeSession.user_id == user_id,
            PracticeSession.language == language,
            PracticeSession.created_at >= since,
            (PracticeSession.completed_at.is_not(None))
            | (PracticeSession.skill == PracticeSkill.CONVERSATION),
        )
    )
    days = set(review_days) | set(practice_days)
    return ProgressOut(
        language=language,
        level=enrollment.level if enrollment else None,
        words=WordStats(total=total, learned=learned, mastered=mastered, due=due),
        skills=skills,
        streak_days=streak(days, now.date()),
        active_days_last_7=sum(1 for d in days if (now.date() - d).days < 7),
    )


def streak(days: set[date], today: date) -> int:
    """Consecutive active days ending today (or yesterday, if today isn't done yet)."""
    day = today if today in days else today - timedelta(days=1)
    count = 0
    while day in days:
        count += 1
        day -= timedelta(days=1)
    return count
